"""Executive report: a Markdown summary plus one CSV per anomaly rule."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from .config import Config


def _fmt_money(value: float) -> str:
    return f"${value:,.2f}"


def build_report(matched: pd.DataFrame, findings: dict[str, pd.DataFrame], cfg: Config) -> str:
    total_ops = matched["ops_amount"].sum()
    total_settled = matched["settlement_total"].sum()
    n_ops = int((matched["ops_amount"] > 0).sum())
    n_issues = sum(len(df) for df in findings.values())

    lines = [
        "# Reconciliation Executive Report",
        "",
        "## Health at a glance",
        "",
        f"- **Transactions reconciled:** {n_ops}",
        f"- **Recorded total:** {_fmt_money(total_ops)}",
        f"- **Settled (billed) total:** {_fmt_money(total_settled)}",
        f"- **Net difference:** {_fmt_money(total_settled - total_ops)}",
        f"- **Rules fired:** {len(findings)} · **flagged rows:** {n_issues}",
        "",
        "## Findings",
        "",
    ]

    if not findings:
        lines.append("✅ No anomalies detected. Sources reconcile within tolerance.")
    else:
        for name, df in findings.items():
            title = name.replace("_", " ").title()
            lines += [f"### 🔴 {title} ({len(df)})", "", df.to_markdown(index=False), ""]

    lines += [
        "",
        "---",
        f"_Generated by Reconciliation Engine · tolerance {cfg.amount_tolerance} MXN_",
    ]
    return "\n".join(lines)


def export_findings_csv(findings: dict[str, pd.DataFrame], cfg: Config) -> list[Path]:
    cfg.output_dir.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    for name, df in findings.items():
        path = cfg.output_dir / f"anomalies_{name}.csv"
        df.to_csv(path, index=False)
        paths.append(path)
    return paths


def export_report(matched: pd.DataFrame, findings: dict[str, pd.DataFrame], cfg: Config) -> Path:
    cfg.output_dir.mkdir(parents=True, exist_ok=True)
    path = cfg.output_dir / "reconciliation_report.md"
    path.write_text(build_report(matched, findings, cfg), encoding="utf-8")
    return path
